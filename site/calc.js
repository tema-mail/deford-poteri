/* Калькулятор потерь клиентов без SEO-сайта. Данные – window.DATA (Вордстат через XMLRiver, см. data.js).
   Модель одна для обеих страниц, коэффициенты – в MODEL, их же показываем на странице открыто. */
(function () {
  var D = window.DATA;
  var MODEL = {
    servis: { sites: 0.5, top: 0.2, conv: 0.08, close: 0.6 },
    avto: { sites: 0.6, top: 0.1, conv: 0.03, close: 0.1, margin: 150000 }
  };
  // Сколько потенциала поиска забирает бизнес в каждом состоянии (допущение, сверим на своих сайтах).
  var STATES = {
    none: { name: 'Сайта нет', take: 0 },
    landing: { name: 'Есть лендинг на одну страницу', take: 0.15 },
    weak: { name: 'Сайт есть, но не продвигается', take: 0.1 }
  };
  // Услуги: запрос Вордстата → название и средний чек (оценка, владелец правит своим).
  var SERVICES = [
    ['ремонт акпп', 'Ремонт АКПП', 70000], ['ремонт вариатора', 'Ремонт вариатора', 70000],
    ['диагностика автомобиля', 'Диагностика', 2500], ['техническое обслуживание автомобиля', 'ТО', 12000],
    ['замена масла', 'Замена масла', 3500], ['развал схождение', 'Развал-схождение', 3000],
    ['шиномонтаж', 'Шиномонтаж', 3500], ['кузовной ремонт', 'Кузовной ремонт', 40000],
    ['покраска автомобиля', 'Покраска', 25000], ['ремонт двигателя', 'Ремонт двигателя', 60000],
    ['капитальный ремонт двигателя', 'Капремонт двигателя', 150000], ['автоэлектрик', 'Автоэлектрик', 6000],
    ['ремонт ходовой', 'Ремонт ходовой', 15000], ['замена ремня грм', 'Замена ремня ГРМ', 15000],
    ['замена тормозных колодок', 'Тормозные колодки', 4000], ['заправка кондиционера автомобиля', 'Заправка кондиционера', 3000],
    ['ремонт турбины', 'Ремонт турбины', 35000], ['ремонт стартера', 'Ремонт стартера', 7000],
    ['ремонт генератора', 'Ремонт генератора', 8000], ['ремонт рулевой рейки', 'Ремонт рулевой рейки', 25000],
    ['замена сцепления', 'Замена сцепления', 25000], ['ремонт форсунок', 'Ремонт форсунок', 20000],
    ['ремонт глушителя', 'Ремонт глушителя', 8000], ['установка сигнализации', 'Сигнализация', 30000],
    ['тонировка', 'Тонировка', 8000], ['шумоизоляция автомобиля', 'Шумоизоляция', 40000],
    ['полировка автомобиля', 'Полировка', 15000], ['химчистка салона автомобиля', 'Химчистка салона', 10000],
    ['детейлинг', 'Детейлинг', 30000], ['оклейка автомобиля пленкой', 'Оклейка плёнкой', 120000],
    ['установка магнитолы', 'Установка магнитолы', 35000], ['ремонт китайских автомобилей', 'Ремонт китайских авто', 15000],
    ['ремонт гибридов', 'Ремонт гибридов', 25000], ['ремонт электромобилей', 'Ремонт электромобилей', 25000],
    ['ремонт бмв', 'Сервис BMW', 20000], ['ремонт мерседес', 'Сервис Mercedes', 20000],
    ['ремонт тойота', 'Сервис Toyota', 12000], ['сервис хавал', 'Сервис Haval', 12000], ['сервис чери', 'Сервис Chery', 12000]
  ];
  var COUNTRIES = [
    ['китая', 'Китай'], ['кореи', 'Корея'], ['японии', 'Япония'], ['германии', 'Германия'], ['европы', 'Европа'],
    ['оаэ', 'ОАЭ'], ['сша', 'США'], ['киргизии', 'Киргизия'], ['беларуси', 'Беларусь'], ['грузии', 'Грузия'],
    ['казахстана', 'Казахстан'], ['армении', 'Армения']
  ];
  // Входят в другие запросы (капремонт – в «ремонт двигателя», марки – в услуги): в общую сумму не идут, в калькуляторе по умолчанию сняты.
  var SUBSET = { 'капитальный ремонт двигателя': 1, 'ремонт бмв': 1, 'ремонт мерседес': 1, 'ремонт тойота': 1, 'сервис хавал': 1, 'сервис чери': 1 };
  // Запросы «рядом» – в основном карты: на сайты уходит вдвое меньше.
  var MAPS = { 'автосервис': 1, 'шиномонтаж': 1, 'автоэлектрик': 1 };
  // Набор обычного сервиса по ремонту – отмечен в калькуляторе по умолчанию.
  var BASE = ['автосервис', 'диагностика автомобиля', 'техническое обслуживание автомобиля', 'замена масла', 'развал схождение',
    'ремонт ходовой', 'замена тормозных колодок', 'ремонт двигателя', 'замена ремня грм', 'замена сцепления', 'автоэлектрик', 'ремонт акпп'];
  var fmt = function (n) { return Math.round(n).toLocaleString('ru-RU'); };
  var get = function (group, q, r) { var g = D[group][q]; return g && g[r] ? g[r] : null; };

  function serviceRows(region) {
    return SERVICES.map(function (s) {
      var d = get('services', s[0], region);
      return { q: s[0], name: s[1], check: s[2], sub: !!SUBSET[s[0]], total: d ? d.total : null, hot: d ? d.hot : null, share: d ? d.share : null, top: d ? d.top : [] };
    }).filter(function (r) { return r.hot !== null; }).sort(function (a, b) { return b.hot - a.hot; });
  }
  function countryRows(region) {
    return COUNTRIES.map(function (c) {
      var parts = ['авто из ', 'автомобили из ', 'машину из '].map(function (p) { return get('cars', p + c[0], region); });
      var ok = parts.filter(Boolean);
      return { key: c[0], name: c[1], total: ok.reduce(function (s, d) { return s + d.total; }, 0),
        hot: ok.reduce(function (s, d) { return s + d.hot; }, 0), measured: ok.length };
    }).filter(function (r) { return r.measured; }).sort(function (a, b) { return b.hot - a.hot; });
  }
  // Клиентов в месяц, которых приносит сайт в топ-3 при данном горячем спросе.
  function clientsServis(hot, q) { var m = MODEL.servis; return hot * (MAPS[q] ? m.sites / 2 : m.sites) * m.top * m.conv * m.close; }
  function dealsAvto(hot) { var m = MODEL.avto; return hot * m.sites * m.top * m.conv * m.close; }
  // Сколько из этого уходит мимо в выбранном состоянии.
  function lost(potential, state) { return potential * (1 - STATES[state].take); }
  // Доля рабочего дня, прошедшая к этому часу (8:00–21:00) – для счётчика «сегодня уже упустили».
  // До 8 утра показываем вчерашний день целиком: { part, label }.
  function dayPart() {
    var d = new Date(), h = d.getHours() + d.getMinutes() / 60;
    if (h < 8) return { part: 1, label: 'За вчерашний день' };
    return { part: Math.min(1, (h - 8) / 13), label: 'Сегодня с 8:00' };
  }
  window.POTERI = { D: D, MODEL: MODEL, STATES: STATES, SERVICES: SERVICES, SUBSET: SUBSET, MAPS: MAPS, BASE: BASE, COUNTRIES: COUNTRIES, fmt: fmt,
    serviceRows: serviceRows, countryRows: countryRows, clientsServis: clientsServis, dealsAvto: dealsAvto, lost: lost, dayPart: dayPart };
})();
